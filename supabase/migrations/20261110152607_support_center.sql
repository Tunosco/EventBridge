ALTER TABLE public.utilisateur
  ADD COLUMN IF NOT EXISTS is_admin BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE IF NOT EXISTS public.support_ticket (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_number TEXT NOT NULL UNIQUE,
  requester_id INTEGER REFERENCES public.utilisateur(id) ON DELETE SET NULL,
  requester_name TEXT NOT NULL,
  requester_email TEXT NOT NULL,
  category TEXT NOT NULL,
  subcategory TEXT NOT NULL,
  message TEXT NOT NULL CHECK (length(btrim(message)) BETWEEN 10 AND 5000),
  booking_reference TEXT,
  attachments_json JSONB NOT NULL DEFAULT '[]'::jsonb,
  priority_score INTEGER NOT NULL CHECK (priority_score BETWEEN 0 AND 100),
  urgency TEXT NOT NULL CHECK (urgency IN ('tres_urgent', 'urgent', 'peu_urgent', 'pas_urgent')),
  priority_reason TEXT NOT NULL,
  recommended_actions_json JSONB NOT NULL DEFAULT '[]'::jsonb,
  needs_human_review BOOLEAN NOT NULL DEFAULT FALSE,
  status TEXT NOT NULL DEFAULT 'nouvelle' CHECK (status IN ('nouvelle', 'en_cours', 'en_attente_reponse', 'resolue', 'fermee')),
  assignee_id INTEGER REFERENCES public.utilisateur(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS support_ticket_priority_idx
  ON public.support_ticket (priority_score DESC, created_at ASC);
CREATE INDEX IF NOT EXISTS support_ticket_requester_idx
  ON public.support_ticket (requester_id, created_at DESC);

CREATE TABLE IF NOT EXISTS public.support_ticket_history (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id INTEGER NOT NULL REFERENCES public.support_ticket(id) ON DELETE CASCADE,
  actor_user_id INTEGER REFERENCES public.utilisateur(id) ON DELETE SET NULL,
  action_type TEXT NOT NULL,
  previous_value_json JSONB,
  new_value_json JSONB,
  note TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS support_ticket_history_ticket_idx
  ON public.support_ticket_history (ticket_id, created_at ASC);

CREATE TABLE IF NOT EXISTS public.support_notification (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id INTEGER NOT NULL REFERENCES public.support_ticket(id) ON DELETE CASCADE,
  notification_type TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  read_at TIMESTAMPTZ
);

ALTER TABLE public.support_ticket ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.support_ticket_history ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.support_notification ENABLE ROW LEVEL SECURITY;