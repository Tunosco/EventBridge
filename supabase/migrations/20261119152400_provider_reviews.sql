-- Reviews submitted by clients and answered by providers.
CREATE TABLE IF NOT EXISTS public.avis_prestataire (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  prestataire_id INTEGER NOT NULL REFERENCES public.prestataire(utilisateur_id) ON DELETE CASCADE,
  client_id INTEGER NOT NULL REFERENCES public.client(utilisateur_id) ON DELETE CASCADE,
  note INTEGER NOT NULL CHECK (note BETWEEN 1 AND 5),
  commentaire TEXT NOT NULL CHECK (length(btrim(commentaire)) BETWEEN 1 AND 4000),
  reponse TEXT,
  date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  date_reponse TIMESTAMPTZ,
  UNIQUE (prestataire_id, client_id)
);

CREATE INDEX IF NOT EXISTS avis_prestataire_owner_idx
  ON public.avis_prestataire (prestataire_id, date_creation DESC);

ALTER TABLE public.avis_prestataire ENABLE ROW LEVEL SECURITY;
